#!/usr/bin/env node
/**
 * FloOwner & FloCafe Arch Linux pacman (.pkg.tar.zst) Package Builder
 * Creates native Arch Linux packages installable with:
 * sudo pacman -U release/flo-owner-control-4.7.2-1-x86_64.pkg.tar.zst
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const rootDir = path.resolve(__dirname, '..');
const releaseDir = path.join(rootDir, 'release');
const stagingDir = path.join(rootDir, 'dist', 'arch-staging');

if (!fs.existsSync(releaseDir)) {
  fs.mkdirSync(releaseDir, { recursive: true });
}

function calculateDirSize(dir) {
  let size = 0;
  if (!fs.existsSync(dir)) return size;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      size += calculateDirSize(full);
    } else if (entry.isFile()) {
      size += fs.statSync(full).size;
    }
  }
  return size;
}

function buildArchOwnerPackage() {
  console.log('[Arch Packager] Assembling flo-owner-control package...');
  const ownerStage = path.join(stagingDir, 'flo-owner-control');
  if (fs.existsSync(ownerStage)) {
    fs.rmSync(ownerStage, { recursive: true, force: true });
  }

  const optDir = path.join(ownerStage, 'opt', 'flo-owner-control');
  const binDir = path.join(ownerStage, 'usr', 'bin');
  const appDir = path.join(ownerStage, 'usr', 'share', 'applications');
  const sysdDir = path.join(ownerStage, 'usr', 'lib', 'systemd', 'user');

  fs.mkdirSync(optDir, { recursive: true });
  fs.mkdirSync(binDir, { recursive: true });
  fs.mkdirSync(appDir, { recursive: true });
  fs.mkdirSync(sysdDir, { recursive: true });

  // Copy app assets
  fs.copyFileSync(
    path.join(rootDir, 'owner-system', 'flo-owner-control.html'),
    path.join(optDir, 'flo-owner-control.html')
  );
  fs.copyFileSync(
    path.join(rootDir, 'owner-system', 'owner-main.cjs'),
    path.join(optDir, 'owner-main.cjs')
  );
  fs.copyFileSync(
    path.join(rootDir, 'owner-system', 'owner-preload.cjs'),
    path.join(optDir, 'owner-preload.cjs')
  );
  fs.copyFileSync(
    path.join(rootDir, 'scripts', 'flocafe-owner-mcp.cjs'),
    path.join(optDir, 'flocafe-owner-mcp.cjs')
  );

  // Desktop launcher
  const desktopSrc = path.join(rootDir, 'owner-system', 'flo-owner-control.desktop');
  const desktopDst = path.join(appDir, 'flo-owner-control.desktop');
  const desktopContent = `[Desktop Entry]
Name=FloOwner Control System
GenericName=POS Fleet Manager
Comment=Standalone remote fleet manager for FloCafe POS
Exec=/usr/bin/flo-owner-control %U
Icon=/opt/flo-owner-control/icon-512.png
Terminal=false
Type=Application
Categories=Office;Finance;Network;
Keywords=FloCafe;POS;remote;fleet;owner;sentinel;
StartupNotify=false
`;
  fs.writeFileSync(desktopDst, desktopContent, 'utf8');
  fs.writeFileSync(path.join(optDir, 'flo-owner-control.desktop'), desktopContent, 'utf8');

  // App icon
  if (fs.existsSync(path.join(rootDir, 'assets', 'icon-512.png'))) {
    fs.copyFileSync(path.join(rootDir, 'assets', 'icon-512.png'), path.join(optDir, 'icon-512.png'));
  }

  // /usr/bin/flo-owner-control executable wrapper
  const binWrapper = `#!/usr/bin/env bash
if command -v electron >/dev/null 2>&1; then
  exec electron /opt/flo-owner-control/owner-main.cjs "$@"
elif command -v xdg-open >/dev/null 2>&1; then
  exec xdg-open /opt/flo-owner-control/flo-owner-control.html
else
  echo "FloOwner Control: open /opt/flo-owner-control/flo-owner-control.html in your browser."
fi
`;
  fs.writeFileSync(path.join(binDir, 'flo-owner-control'), binWrapper, { mode: 0o755 });

  // /usr/bin/flocafe-owner-mcp executable wrapper
  const mcpWrapper = `#!/usr/bin/env bash
exec /usr/bin/node /opt/flo-owner-control/flocafe-owner-mcp.cjs "$@"
`;
  fs.writeFileSync(path.join(binDir, 'flocafe-owner-mcp'), mcpWrapper, { mode: 0o755 });

  // Systemd user unit
  const sysdContent = `[Unit]
Description=FloCafe Owner MCP Server (stdio -> AI agents)
After=network.target

[Service]
Type=simple
ExecStart=/usr/bin/node /opt/flo-owner-control/flocafe-owner-mcp.cjs
Restart=always
RestartSec=5
Environment=NODE_ENV=production

[Install]
WantedBy=default.target
`;
  fs.writeFileSync(path.join(sysdDir, 'flocafe-owner-mcp.service'), sysdContent, 'utf8');

  // .PKGINFO
  const installedSize = calculateDirSize(ownerStage);
  const epoch = Math.floor(Date.now() / 1000);
  const pkginfo = `# Generated by FloCafe Arch Packager
pkgname = flo-owner-control
pkgbase = flo-owner-control
pkgver = 4.7.2-1
pkgdesc = FloOwner Control System — Standalone native remote fleet manager for FloCafe POS
url = https://github.com/omrshrifmo/FloCafe2
builddate = ${epoch}
packager = Omar Shrif <https://github.com/omrshrifmo>
size = ${installedSize}
arch = x86_64
license = MIT
depend = nodejs
optdepend = xdg-utils: Open browser dashboard fallback
optdepend = tailscale: Zero-cost P2P mesh network
`;
  fs.writeFileSync(path.join(ownerStage, '.PKGINFO'), pkginfo, 'utf8');

  // Archive creation
  const pkgFile = path.join(releaseDir, 'flo-owner-control-4.7.2-1-x86_64.pkg.tar.zst');
  const tarCmd = `tar -c --zstd -f "${pkgFile}" -C "${ownerStage}" .PKGINFO opt usr`;
  execSync(tarCmd, { stdio: 'inherit' });
  console.log(`[Arch Packager] Created: ${pkgFile} (${fs.statSync(pkgFile).size} bytes)`);
}

function buildArchSentinelPackage() {
  console.log('[Arch Packager] Assembling flocafe-sentinel package...');
  const sentinelStage = path.join(stagingDir, 'flocafe-sentinel');
  if (fs.existsSync(sentinelStage)) {
    fs.rmSync(sentinelStage, { recursive: true, force: true });
  }

  const optDir = path.join(sentinelStage, 'opt', 'flocafe');
  const binDir = path.join(sentinelStage, 'usr', 'bin');
  const sysdDir = path.join(sentinelStage, 'usr', 'lib', 'systemd', 'user');

  fs.mkdirSync(optDir, { recursive: true });
  fs.mkdirSync(binDir, { recursive: true });
  fs.mkdirSync(sysdDir, { recursive: true });

  if (fs.existsSync(path.join(rootDir, 'scripts', 'flocafe-sentinel.cjs'))) {
    fs.copyFileSync(
      path.join(rootDir, 'scripts', 'flocafe-sentinel.cjs'),
      path.join(optDir, 'flocafe-sentinel.cjs')
    );
  }

  const binWrapper = `#!/usr/bin/env bash
exec /usr/bin/node /opt/flocafe/flocafe-sentinel.cjs "$@"
`;
  fs.writeFileSync(path.join(binDir, 'flocafe-sentinel'), binWrapper, { mode: 0o755 });

  const sysdContent = `[Unit]
Description=FloCafe Sentinel Background OS Daemon
After=network.target

[Service]
Type=simple
WorkingDirectory=/opt/flocafe
ExecStart=/usr/bin/node /opt/flocafe/flocafe-sentinel.cjs
Restart=always
RestartSec=5
Environment=NODE_ENV=production
Environment=SENTINEL_PORT=3009

[Install]
WantedBy=default.target
`;
  fs.writeFileSync(path.join(sysdDir, 'flocafe-sentinel.service'), sysdContent, 'utf8');

  const installedSize = calculateDirSize(sentinelStage);
  const epoch = Math.floor(Date.now() / 1000);
  const pkginfo = `# Generated by FloCafe Arch Packager
pkgname = flocafe-sentinel
pkgbase = flocafe-sentinel
pkgver = 4.7.2-1
pkgdesc = FloCafe Sovereign Offline-First POS & Sentinel OS Daemon
url = https://github.com/omrshrifmo/FloCafe2
builddate = ${epoch}
packager = Omar Shrif <https://github.com/omrshrifmo>
size = ${installedSize}
arch = x86_64
license = MIT
depend = nodejs
optdepend = tailscale: Zero-cost P2P mesh network
optdepend = wireguard-tools: WireGuard P2P VPN support
`;
  fs.writeFileSync(path.join(sentinelStage, '.PKGINFO'), pkginfo, 'utf8');

  const pkgFile = path.join(releaseDir, 'flocafe-sentinel-4.7.2-1-x86_64.pkg.tar.zst');
  const tarCmd = `tar -c --zstd -f "${pkgFile}" -C "${sentinelStage}" .PKGINFO opt usr`;
  execSync(tarCmd, { stdio: 'inherit' });
  console.log(`[Arch Packager] Created: ${pkgFile} (${fs.statSync(pkgFile).size} bytes)`);
}

try {
  buildArchOwnerPackage();
  buildArchSentinelPackage();
  console.log('✅ Arch Linux pacman packages created successfully in release/');
} catch (err) {
  console.error('❌ Arch Linux packaging error:', err.message);
  process.exit(1);
}
